// SQL generator and math check for loading the scrubbed fixtures (fixtures/inputs.json) into the
// NEW Supabase project. Driven by harness/db/remote-seed.sh; it never talks to a database itself.
//
//   node --experimental-strip-types harness/db/seed-fixtures.ts seed-sql <owner-email>
//   node --experimental-strip-types harness/db/seed-fixtures.ts reset-sql
//   node --experimental-strip-types harness/db/seed-fixtures.ts readback-sql
//   node --experimental-strip-types harness/db/seed-fixtures.ts check <readback.json>
//
// Only fixture data: one test location, its settings, staff S01-S24 and the 210 shifts. Row ids are
// derived from the fixture keys, so the seed is reproducible and the check can map ids back.
import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import assert from "node:assert/strict";
import { computeShift, fromDbShift, payrollTotalsByStaff } from "../../src/engine/index.ts";

const read = (p: string) => JSON.parse(readFileSync(new URL(p, import.meta.url), "utf8"));
const inputs = read("../../fixtures/inputs.json");

export const LOCATION_NAME = "TEST: scrubbed fixtures (not real payroll)";

/** Deterministic uuid for a fixture key (md5, formatted as a uuid). */
export function fid(key: string): string {
  const h = createHash("md5").update(`ttp-fixture:${key}`).digest("hex");
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-${h.slice(12, 16)}-${h.slice(16, 20)}-${h.slice(20, 32)}`;
}
export const LOCATION_ID = fid("location");
const staffUuid = (s: string | null) => (s == null ? null : fid(`staff:${s}`));

const lit = (v: unknown): string => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "number") {
    if (!Number.isFinite(v)) throw new Error(`non-finite number ${v}`);
    return String(v);
  }
  if (typeof v === "boolean") return v ? "true" : "false";
  return `'${String(v).replace(/'/g, "''")}'`;
};
const values = (rows: unknown[][]) => rows.map((r) => `(${r.map(lit).join(", ")})`).join(",\n  ");
const insert = (table: string, cols: string[], rows: unknown[][]) =>
  rows.length ? `insert into public.${table} (${cols.join(", ")}) values\n  ${values(rows)};\n` : "";

const SETTINGS_COLS = [
  "bar_tip_pct", "runner_busser_tip_pct", "bartender_tip_pct", "max_tipout_pct", "rb_basis",
  "rounding_mode", "use_net_sales", "sales_tax_pct", "cc_fee_enabled", "cc_fee_pct",
  "weight_runner", "weight_busser", "weight_bar_back", "weight_hostess",
];

export function seedSql(ownerEmail: string): string {
  assert.deepStrictEqual(Object.keys(inputs.settings).sort(), [...SETTINGS_COLS].sort(), "settings columns");
  const servers: unknown[][] = [], serverMembers: unknown[][] = [];
  const bartenders: unknown[][] = [], bartenderMembers: unknown[][] = [];
  const support: unknown[][] = [], shifts: unknown[][] = [];
  for (const sh of inputs.shifts) {
    const sid = fid(`shift:${sh.key}`);
    shifts.push([sid, LOCATION_ID, sh.shift_date, sh.period, sh.support_split_mode]);
    sh.servers.forEach((e: any, i: number) => {
      const eid = fid(`server:${sh.key}:${i}`);
      servers.push([eid, sid, staffUuid(e.staff_id), e.cash_owed, e.credit_tips, e.lbw_sales,
        e.total_sales, e.bar_tip_override, e.rb_tip_override, e.split_mode]);
      for (const m of e.members) serverMembers.push([eid, staffUuid(m.staff_id), m.hours_worked]);
    });
    sh.bartenders.forEach((e: any, i: number) => {
      const eid = fid(`bartender:${sh.key}:${i}`);
      bartenders.push([eid, sid, staffUuid(e.staff_id), e.cash_owed, e.credit_tips, e.total_sales,
        e.rb_tip_override, e.split_mode]);
      for (const m of e.members) bartenderMembers.push([eid, staffUuid(m.staff_id), m.hours_worked]);
    });
    for (const p of sh.support) support.push([sid, staffUuid(p.staff_id), p.hours_worked, p.role]);
  }
  const s = inputs.settings;
  return `-- Generated by harness/db/seed-fixtures.ts from fixtures/inputs.json. Scrubbed fixture data only.
begin;
do $guard$
begin
  -- Only an otherwise empty project: any location at all means real data may be present.
  if exists (select 1 from public.locations) then
    raise exception 'refusing to seed: public.locations is not empty';
  end if;
  if not exists (select 1 from auth.users where lower(email) = lower(${lit(ownerEmail)})) then
    raise exception 'owner user % not found in auth.users; create it first (Authentication > Users > Add user)', ${lit(ownerEmail)};
  end if;
end $guard$;

insert into public.locations (id, name, owner_user_id, timezone, setup_completed_at)
select ${lit(LOCATION_ID)}, ${lit(LOCATION_NAME)}, id, 'America/New_York', now()
from auth.users where lower(email) = lower(${lit(ownerEmail)});
-- locations_create_default_settings has created the app_settings row; set the fixture settings.
update public.app_settings set establishment_name = ${lit(LOCATION_NAME)},
  ${SETTINGS_COLS.map((c) => `${c} = ${lit(s[c])}`).join(",\n  ")}
where location_id = ${lit(LOCATION_ID)};
insert into public.location_members (location_id, user_id, role)
select ${lit(LOCATION_ID)}, id, 'owner' from auth.users where lower(email) = lower(${lit(ownerEmail)});

${insert("staff", ["id", "location_id", "name", "server_number", "role", "active"],
    inputs.staff.map((p: any) => [staffUuid(p.id), LOCATION_ID, `Staff ${p.id}`, p.id.slice(1), p.role, p.active]))}
${insert("shifts", ["id", "location_id", "shift_date", "period", "support_split_mode"], shifts)}
${insert("shift_servers", ["id", "shift_id", "staff_id", "cash_owed", "credit_tips", "lbw_sales", "total_sales",
    "bar_tip_override", "rb_tip_override", "split_mode"], servers)}
${insert("shift_server_members", ["shift_server_id", "staff_id", "hours_worked"], serverMembers)}
${insert("shift_bartenders", ["id", "shift_id", "staff_id", "cash_owed", "credit_tips", "total_sales",
    "rb_tip_override", "split_mode"], bartenders)}
${insert("shift_bartender_members", ["shift_bartender_id", "staff_id", "hours_worked"], bartenderMembers)}
${insert("shift_support", ["shift_id", "staff_id", "hours_worked", "role"], support)}
-- The audit triggers logged the seed itself (settings update, each override insert) with no user.
-- Those rows are not edits anyone made, so drop them; audits record UI edits from here on.
delete from public.settings_audit where location_id = ${lit(LOCATION_ID)};
delete from public.tip_override_audit where location_id = ${lit(LOCATION_ID)};
commit;
`;
}

export function resetSql(): string {
  // Explicit order: entry rows reference staff ON DELETE RESTRICT, so shifts go before the location.
  return `begin;
delete from public.shifts where location_id = ${lit(LOCATION_ID)};
delete from public.locations where id = ${lit(LOCATION_ID)};
commit;
`;
}

/** One json value, shaped like the payroll screen's selects (reports.tsx), rows in insertion order. */
export function readbackSql(locationId: string = LOCATION_ID): string {
  const L = lit(locationId);
  return `select json_build_object(
  'counts', json_build_object(
    'locations', (select count(*) from public.locations),
    'staff', (select count(*) from public.staff where location_id = ${L}),
    'shifts', (select count(*) from public.shifts where location_id = ${L}),
    'other_location_rows', (select count(*) from public.shifts where location_id is distinct from ${L})
      + (select count(*) from public.staff where location_id is distinct from ${L})),
  'settings', (select row_to_json(a) from public.app_settings a where a.location_id = ${L}),
  'staff', (select json_agg(json_build_object('id', st.id, 'role', st.role) order by st.ctid)
            from public.staff st where st.location_id = ${L}),
  'shifts', (select json_agg(json_build_object(
      'id', s.id, 'shift_date', s.shift_date, 'period', s.period,
      'shift_servers', coalesce((select json_agg(json_build_object(
          'staff_id', e.staff_id, 'cash_owed', e.cash_owed, 'credit_tips', e.credit_tips,
          'lbw_sales', e.lbw_sales, 'bar_tip_override', e.bar_tip_override,
          'rb_tip_override', e.rb_tip_override, 'split_mode', e.split_mode,
          'shift_server_members', coalesce((select json_agg(json_build_object(
              'staff_id', m.staff_id, 'hours_worked', m.hours_worked) order by m.ctid)
            from public.shift_server_members m where m.shift_server_id = e.id), '[]'))
        order by e.ctid) from public.shift_servers e where e.shift_id = s.id), '[]'),
      'shift_bartenders', coalesce((select json_agg(json_build_object(
          'staff_id', e.staff_id, 'cash_owed', e.cash_owed, 'credit_tips', e.credit_tips,
          'rb_tip_override', e.rb_tip_override, 'split_mode', e.split_mode,
          'shift_bartender_members', coalesce((select json_agg(json_build_object(
              'staff_id', m.staff_id, 'hours_worked', m.hours_worked) order by m.ctid)
            from public.shift_bartender_members m where m.shift_bartender_id = e.id), '[]'))
        order by e.ctid) from public.shift_bartenders e where e.shift_id = s.id), '[]'),
      'shift_support', coalesce((select json_agg(json_build_object(
          'staff_id', p.staff_id, 'hours_worked', p.hours_worked, 'role', p.role) order by p.ctid)
        from public.shift_support p where p.shift_id = s.id), '[]'),
      'support_split_mode', s.support_split_mode)
    order by s.shift_date, s.period) from public.shifts s where s.location_id = ${L})
) as j`;
}

/** Runs the payroll engine on rows read back from the database and compares with expected_v1.json.
 *  Staff ids map to S01..S24 either by the seed's derived ids (default) or, for the migrated
 *  production data, by sorting the location's staff ids: that is how the fixtures were numbered. */
export function check(db: any, mapping: "seed" | "by-sorted-staff-id" = "seed"): string[] {
  const expected = read("../../fixtures/expected_v1.json");
  const problems: string[] = [];
  const toFixture = mapping === "seed"
    ? new Map<string, string>(inputs.staff.map((p: any) => [staffUuid(p.id)!, p.id]))
    : new Map<string, string>([...db.staff.map((s: any) => s.id)].sort().map((u: string, i: number) => [u, inputs.staff[i]?.id ?? `extra-${i}`]));
  const unmap = (x: unknown) =>
    JSON.parse(JSON.stringify(x).replace(/"([0-9a-f-]{36})"/g, (m, u) => (toFixture.has(u) ? `"${toFixture.get(u)}"` : m)));

  if (db.counts.locations !== 1) problems.push(`expected exactly 1 location, found ${db.counts.locations}`);
  if (db.counts.other_location_rows !== 0) problems.push(`${db.counts.other_location_rows} staff/shift rows outside the test location`);
  if (db.counts.staff !== inputs.staff.length) problems.push(`staff: ${db.counts.staff} rows, fixture has ${inputs.staff.length}`);
  if (db.counts.shifts !== inputs.shifts.length) problems.push(`shifts: ${db.counts.shifts} rows, fixture has ${inputs.shifts.length}`);

  // Exactly what reports.tsx does: staffRole from staff.role, settings = the app_settings row.
  const staffRole = new Map<string, string>(db.staff.map((s: any) => [s.id, s.role]));
  const settings = db.settings;
  const byKey = new Map<string, any>(expected.shifts.map((e: any) => [e.key, e.expected]));
  let matched = 0;
  for (const row of db.shifts) {
    const key = `${row.shift_date}-${row.period}`;
    const got = unmap(computeShift(fromDbShift(row), settings, { staffRole }, "v1"));
    try {
      assert.deepStrictEqual(got, byKey.get(key));
      matched++;
    } catch {
      problems.push(`shift ${key}: engine result on database rows differs from expected_v1`);
    }
  }

  const totals = unmap(Object.fromEntries(payrollTotalsByStaff(db.shifts, settings, staffRole)));
  const exp = expected.period_totals_by_staff;
  const ids = (o: object) => Object.keys(o).sort();
  if (JSON.stringify(ids(totals)) !== JSON.stringify(ids(exp))) problems.push("period totals: staff set differs");
  let cents = 0;
  for (const id of Object.keys(exp)) {
    for (const k of Object.keys(exp[id])) {
      const a = Math.round((totals[id]?.[k] ?? NaN) * 100), b = Math.round(exp[id][k] * 100);
      if (a !== b) problems.push(`period total ${id}.${k}: database ${a / 100}, expected ${b / 100}`);
      else cents++;
    }
  }
  console.log(`shifts matching expected_v1: ${matched} of ${expected.shifts.length}`);
  console.log(`period totals matching to the cent: ${cents} values across ${ids(exp).length} staff`);
  const sum = (f: string) => Object.values(totals as Record<string, any>).reduce((t, p) => t + p[f], 0);
  console.log(`credit tips $${sum("credit_tips").toFixed(2)}, take-home $${sum("takehome").toFixed(2)}`);
  return problems;
}

const [cmd, arg, arg2] = process.argv.slice(2);
if (import.meta.url === `file://${process.argv[1]}`) {
  if (cmd === "seed-sql") {
    if (!arg || !/^[^@\s']+@[^@\s']+$/.test(arg)) throw new Error("usage: seed-sql <owner-email>");
    process.stdout.write(seedSql(arg));
  } else if (cmd === "reset-sql") process.stdout.write(resetSql());
  else if (cmd === "readback-sql") process.stdout.write(readbackSql(arg));
  else if (cmd === "check") {
    const problems = check(JSON.parse(readFileSync(arg, "utf8")), (arg2 as "by-sorted-staff-id") || "seed");
    if (problems.length) {
      console.error(`MISMATCH (${problems.length}):\n  ${problems.slice(0, 40).join("\n  ")}`);
      process.exit(1);
    }
    console.log("payroll math on the database rows equals fixtures/expected_v1.json");
  } else {
    console.error("usage: seed-sql <owner-email> | reset-sql | readback-sql | check <file>");
    process.exit(2);
  }
}
