// Shared helpers for the synthetic fixtures. Used by gen-synthetic.ts (writes the
// fixture) and synthetic.test.ts (checks it). Both run the frozen v1 reference pipeline.
import { readFileSync } from "node:fs";
import { computeShiftV1 } from "./reference-pipeline-v1.ts";
import { SYNTHETIC_CASES, SYNTHETIC_STAFF, type SyntheticCase } from "./synthetic-cases.ts";

const r2 = (n: number) => Math.round(n * 100) / 100;

export const liveSettings = () =>
  JSON.parse(readFileSync(new URL("../fixtures/inputs.json", import.meta.url), "utf8")).settings;

/** Effective settings for a case: Carson's live settings with the case's overrides.
 *  Round-tripped through JSON so an `undefined` override removes the key, exactly as it
 *  will be read back from the fixture file. */
export const settingsFor = (c: SyntheticCase) =>
  JSON.parse(JSON.stringify({ ...liveSettings(), ...c.settings_overrides }));

export const syntheticStaffRole = () => new Map(SYNTHETIC_STAFF.map((s) => [s.id, s.role]));

/** Same observation formula as fixtures/expected_v1.json (verified against all 210 shifts). */
export function observations(shift: any, expected: any) {
  let tips = 0;
  for (const e of [...shift.servers, ...shift.bartenders]) tips += e.credit_tips;
  let allocated = 0;
  for (const p of Object.values(expected.per_person) as any[]) allocated += p.takehome;
  return {
    tips_in: r2(tips),
    allocated_takehome: r2(allocated),
    conservation_gap: r2(allocated - tips),
    support_staff_count: shift.support.length,
  };
}

export function buildSyntheticFixture() {
  const staffRole = syntheticStaffRole();
  return {
    engine:
      "harness/reference-pipeline-v1.ts (frozen v1) — generated by harness/gen-synthetic.ts; do not hand-edit",
    staff: SYNTHETIC_STAFF,
    cases: SYNTHETIC_CASES.map((c) => {
      const settings = settingsFor(c);
      const shift = JSON.parse(JSON.stringify(c.shift));
      const expected = JSON.parse(JSON.stringify(computeShiftV1(shift, settings, staffRole)));
      return {
        key: shift.key,
        name: c.name,
        covers: c.covers,
        settings,
        shift,
        expected,
        observations: observations(shift, expected),
      };
    }),
  };
}
